import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
const source = (await readFile(new URL("../src/lib/dsa-execution/python/runner_harness.py", import.meta.url), "utf8")).replaceAll("\r\n", "\n");
const sha = createHash("sha256").update(source).digest("hex");
const generated = `// Generated by scripts/prepare-python-harness.mjs. Do not edit.\nexport const HARNESS_SHA256 = ${JSON.stringify(sha)};\nexport const HARNESS_SOURCE = ${JSON.stringify(source)};\n`;
const outputs = ["../src/lib/dsa-execution/python/harness.generated.ts", "../public/dsa/runner-harness.mjs"];
for (const path of outputs) {
  const target = new URL(path, import.meta.url);
  if (process.argv.includes("--check")) {
    if (await readFile(target, "utf8").catch(() => "") !== generated) throw new Error(`Harness parity failed: ${path}. Run npm run dsa:harness.`);
  } else { await mkdir(new URL(".", target), { recursive: true }); await writeFile(target, generated); }
}
console.log(`Python harness SHA-256 ${sha}${process.argv.includes("--check") ? " (parity verified)" : ""}`);
